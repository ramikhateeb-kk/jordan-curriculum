-- Run once in Supabase SQL Editor to enable editable subject-specific assessment prompts.
create table if not exists public.assessment_prompts (
    id bigint generated by default as identity primary key,
    subject text not null,
    grade integer not null check (grade between 1 and 12),
    semester integer not null default 1 check (semester in (1, 2)),
    prompt text not null,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint assessment_prompts_subject_grade_semester_key unique (subject, grade, semester)
);
create index if not exists assessment_prompts_lookup_idx
    on public.assessment_prompts (grade, semester, subject, active);
create or replace function public.set_assessment_prompts_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;
drop trigger if exists assessment_prompts_updated_at on public.assessment_prompts;
create trigger assessment_prompts_updated_at before update on public.assessment_prompts
for each row execute function public.set_assessment_prompts_updated_at();
