# -*- coding: utf-8 -*-
"""lesson_plan.py - خطط الدروس اليومية وفق النموذج الوزاري الأردني"""

def generate_lesson_plan(grade: str, subject: str, lesson_title: str) -> str:
    return f"""
نموذج خطة درس يومية - وزارة التربية والتعليم الأردنية
-------------------------------------------------------
المادة: {subject} | الصف: {grade}
عنوان الدرس: {lesson_title}

1. النتاجات العامة والخاصة:
   - يتوقع من الطلبة تحقيق النتاجات المعرفية والوجدانية والمهارية المحددة في دليل المعلم.
2. استراتيجيات التدريس:
   - التعلم التعاوني، التفكير الناقد، الاستقصاء، حل المشكلات.
3. استراتيجيات وأدوات التقويم:
   - التقويم التكويني والملاحظة وسلم التقدير العددي واللفظي.
4. المواد والتجهيزات:
   - الكتاب المدرسي، كتاب الأنشطة والتمارين، السبورة التفاعلية.
5. الإجراءات التنفيذية للدرس:
   - التهيئة الحافزة (5 دقائق)
   - العرض والأنشطة الجماعية (25 دقيقة)
   - التقويم الختامي والغلق (10 دقائق)
   - الواجب البيتي والمتابعة (5 دقائق)
""".strip()
